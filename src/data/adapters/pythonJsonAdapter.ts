const ISO_DATE_RE = /^\d{4}-\d{2}-\d{2}$/;
const HH_MM_RE = /^([01]\d|2[0-3]):([0-5]\d)$/;

export function loadDemoDataset(): FireLensDataset {
  return DEMO_DATASET;
}

function normalizeAcqTimeUtc(rawTime: unknown): string | null {
  if (rawTime === null || rawTime === undefined || rawTime === '') return null;
  if (typeof rawTime === 'number' && Number.isInteger(rawTime) && rawTime >= 0 && rawTime <= 2359) {
    const padded = String(rawTime).padStart(4, '0');
    const hh = Number(padded.slice(0, 2));
    const mm = Number(padded.slice(2, 4));
    if (hh <= 23 && mm <= 59) return `${padded.slice(0, 2)}:${padded.slice(2, 4)}`;
    return null;
  }
  if (typeof rawTime === 'string') {
    const trimmed = rawTime.trim().replace(/\s*UTC$/i, '');
    if (HH_MM_RE.test(trimmed)) return trimmed;
    if (/^\d{3,4}$/.test(trimmed)) {
      const padded = trimmed.padStart(4, '0');
      const candidate = `${padded.slice(0, 2)}:${padded.slice(2, 4)}`;
      if (HH_MM_RE.test(candidate)) return candidate;
    }
  }
  return null;
}

function isValidCompleteness(v: unknown): v is CompletenessStatus {
  return v === 'complete' || v === 'partial' || v === 'missing';
}

function isValidViirsLevel(v: unknown): v is ViirsConfidenceLevel {
  return v === 'low' || v === 'nominal' || v === 'high';
}

function parseIsoDateParts(dateStr: unknown): { date: string; year: number; month: number } | null {
  if (typeof dateStr !== 'string' || !ISO_DATE_RE.test(dateStr)) return null;
  const parsed = new Date(`${dateStr}T00:00:00Z`);
  if (Number.isNaN(parsed.getTime())) return null;
  const year = Number(dateStr.slice(0, 4));
  const month = Number(dateStr.slice(5, 7));
  const day = Number(dateStr.slice(8, 10));
  if (
    parsed.getUTCFullYear() !== year ||
    parsed.getUTCMonth() + 1 !== month ||
    parsed.getUTCDate() !== day
  ) {
    return null;
  }
  return { date: dateStr, year, month };
}

/**
 * Strictly validates external JSON generated by a Python MODIS/VIIRS processing pipeline.
 * Checks structure, types, coordinates, ISO dates, missing/empty values, and verified harmonization results.
 */
export function parseAndValidateFireLensJson(rawJson: string): DatasetParseOutcome {
  if (!rawJson || !rawJson.trim()) {
    return { ok: false, error: 'Файл JSON пуст' };
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(rawJson);
  } catch (err) {
    return {
      ok: false,
      error: 'Некорректный синтаксис JSON',
      details: err instanceof Error ? err.message : 'Ошибка разбора JSON',
    };
  }

  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
    return {
      ok: false,
      error: 'Неверная корневая структура файла',
      details: 'Ожидался JSON-объект формата FireLensDataset.',
    };
  }

  const obj = parsed as Record<string, unknown>;

  if (!Array.isArray(obj.regions) || obj.regions.length === 0) {
    return {
      ok: false,
      error: 'Отсутствует список регионов',
      details: 'Поле "regions" должно быть непустым массивом.',
    };
  }

  if (!obj.dataByRegion || typeof obj.dataByRegion !== 'object' || Array.isArray(obj.dataByRegion)) {
    return {
      ok: false,
      error: 'Отсутствуют данные по регионам',
      details: 'Поле "dataByRegion" должно быть объектом-словарём по идентификаторам регионов.',
    };
  }

  const yearRangeRaw = obj.yearRange;
  if (
    !Array.isArray(yearRangeRaw) ||
    yearRangeRaw.length !== 2 ||
    typeof yearRangeRaw[0] !== 'number' ||
    typeof yearRangeRaw[1] !== 'number' ||
    !Number.isInteger(yearRangeRaw[0]) ||
    !Number.isInteger(yearRangeRaw[1]) ||
    yearRangeRaw[0] < 1995 ||
    yearRangeRaw[1] > 2100 ||
    yearRangeRaw[0] > yearRangeRaw[1]
  ) {
    return {
      ok: false,
      error: 'Некорректный диапазон лет (yearRange)',
      details: 'Ожидается массив [startYear, endYear], где 1995 <= startYear <= endYear <= 2100.',
    };
  }

  const validatedRegions: RegionDefinition[] = [];
  const seenRegionIds = new Set<string>();

  for (let i = 0; i < obj.regions.length; i++) {
    const r = obj.regions[i];
    if (!r || typeof r !== 'object') {
      return { ok: false, error: `Некорректная запись региона #${i + 1}` };
    }
    const reg = r as Record<string, unknown>;
    if (
      typeof reg.id !== 'string' ||
      !reg.id.trim() ||
      typeof reg.name !== 'string' ||
      !reg.name.trim() ||
      !Array.isArray(reg.center) ||
      reg.center.length !== 2
    ) {
      return {
        ok: false,
        error: `Неполные метаданные региона #${i + 1}`,
        details: 'Каждый регион должен содержать непустые id, name и center [lng, lat].',
      };
    }

    if (seenRegionIds.has(reg.id)) {
      return { ok: false, error: `Дублирующийся идентификатор региона "${reg.id}"` };
    }
    seenRegionIds.add(reg.id);

    const [lng, lat] = reg.center as [unknown, unknown];
    if (
      typeof lng !== 'number' ||
      typeof lat !== 'number' ||
      !Number.isFinite(lng) ||
      !Number.isFinite(lat) ||
      lng < -180 ||
      lng > 180 ||
      lat < -90 ||
      lat > 90
    ) {
      return {
        ok: false,
        error: `Координаты центра региона "${reg.name}" вне допустимых пределов`,
      };
    }

    validatedRegions.push({
      id: reg.id,
      name: reg.name,
      isoNumeric: typeof reg.isoNumeric === 'string' ? reg.isoNumeric : undefined,
      usStateFips: typeof reg.usStateFips === 'string' ? reg.usStateFips : undefined,
      boundaryType:
        reg.boundaryType === 'verified_geojson' || reg.boundaryType === 'study_bbox'
          ? reg.boundaryType
          : typeof reg.isoNumeric === 'string' || typeof reg.usStateFips === 'string'
            ? 'verified_geojson'
            : 'study_bbox',
      center: [lng, lat],
      zoom: typeof reg.zoom === 'number' && Number.isFinite(reg.zoom) ? reg.zoom : 4.2,
      bounds:
        reg.bounds && typeof reg.bounds === 'object'
          ? (reg.bounds as RegionDefinition['bounds'])
          : {
              west: Math.max(-180, lng - 8),
              south: Math.max(-85, lat - 6),
              east: Math.min(180, lng + 8),
              north: Math.min(85, lat + 6),
            },
      labelCoords: Array.isArray(reg.labelCoords) && reg.labelCoords.length === 2
        ? (reg.labelCoords as [number, number])
        : [lng, lat],
    });
  }

  const dataByRegionInput = obj.dataByRegion as Record<string, unknown>;
  const validatedDataByRegion: Record<string, RegionDataset> = {};
  const dataMode = obj.dataMode === 'demo' || obj.isDemo === true ? 'demo' : 'real';

  for (const region of validatedRegions) {
    const rawRegionData = dataByRegionInput[region.id];
    if (rawRegionData === undefined || rawRegionData === null) {
      validatedDataByRegion[region.id] = {
        regionId: region.id,
        annualSeries: [],
        weeklyActivity: [],
        hotspots: [],
        harmonization: null,
      };
      continue;
    }

    if (typeof rawRegionData !== 'object' || Array.isArray(rawRegionData)) {
      return {
        ok: false,
        error: `Некорректный формат данных для региона "${region.name}"`,
      };
    }

    const rd = rawRegionData as Record<string, unknown>;

    // Validate hotspots
    if (rd.hotspots !== undefined && !Array.isArray(rd.hotspots)) {
      return {
        ok: false,
        error: `Поле hotspots в регионе "${region.name}" должно быть массивом`,
      };
    }
    const hotspotsRaw = Array.isArray(rd.hotspots) ? rd.hotspots : [];
    const validHotspots: HotspotObservation[] = [];

    for (let idx = 0; idx < hotspotsRaw.length; idx++) {
      const h = hotspotsRaw[idx] as Record<string, unknown>;
      if (!h || typeof h !== 'object') {
        return {
          ok: false,
          error: `Некорректный объект наблюдения #${idx + 1} в регионе "${region.name}"`,
        };
      }
      if (
        typeof h.lat !== 'number' ||
        typeof h.lng !== 'number' ||
        !Number.isFinite(h.lat) ||
        !Number.isFinite(h.lng) ||
        h.lat < -90 ||
        h.lat > 90 ||
        h.lng < -180 ||
        h.lng > 180
      ) {
        return {
          ok: false,
          error: `Некорректные координаты очага #${idx + 1} в регионе "${region.name}"`,
          details: 'Широта должна быть в [-90..90], долгота — в [-180..180].',
        };
      }

      if (h.sensor !== 'MODIS' && h.sensor !== 'VIIRS') {
        return {
          ok: false,
          error: `Неизвестный сенсор "${String(h.sensor)}" в очаге #${idx + 1}`,
          details: 'Допустимые значения sensor: "MODIS" или "VIIRS".',
        };
      }

      let resolvedDate: string;
      let resolvedYear: number;
      let resolvedMonth: number;

      if (h.date !== undefined) {
        const parsedDate = parseIsoDateParts(h.date);
        if (!parsedDate) {
          return {
            ok: false,
            error: `Некорректная дата "${String(h.date)}" в очаге #${idx + 1}`,
            details: 'Ожидается корректная ISO-дата формата YYYY-MM-DD.',
          };
        }
        resolvedDate = parsedDate.date;
        resolvedYear = parsedDate.year;
        resolvedMonth = parsedDate.month;
      } else if (typeof h.year === 'number' && Number.isInteger(h.year)) {
        resolvedYear = h.year;
        resolvedMonth =
          typeof h.month === 'number' ? Math.min(12, Math.max(1, Math.round(h.month))) : 6;
        resolvedDate = `${resolvedYear}-${String(resolvedMonth).padStart(2, '0')}-15`;
      } else {
        return {
          ok: false,
          error: `Отсутствует дата (date / year) в очаге #${idx + 1}`,
        };
      }

      if (typeof h.frpMw !== 'number' || !Number.isFinite(h.frpMw) || h.frpMw < 0) {
        return {
          ok: false,
          error: `Некорректное значение FRP в очаге #${idx + 1}`,
          details: 'Поле frpMw должно быть неотрицательным числом (МВт).',
        };
      }

      const modisConf =
        h.sensor === 'MODIS'
          ? typeof h.modisConfidencePct === 'number'
            ? Math.min(100, Math.max(0, h.modisConfidencePct))
            : typeof h.confidence === 'number'
              ? Math.min(100, Math.max(0, h.confidence))
              : null
          : null;

      const viirsConf =
        h.sensor === 'VIIRS'
          ? isValidViirsLevel(h.viirsConfidenceLevel)
            ? h.viirsConfidenceLevel
            : null
          : null;

      const resolvedAcqTime = normalizeAcqTimeUtc(h.acqTimeUtc ?? h.acq_time ?? h.acqTime);
      const resolvedDayNight =
        h.dayNight === 'D' || h.dayNight === 'N'
          ? h.dayNight
          : h.daynight === 'D' || h.daynight === 'N'
            ? (h.daynight as 'D' | 'N')
            : null;

      validHotspots.push({
        id: typeof h.id === 'string' && h.id.trim() ? h.id : `${region.id}-${idx}`,
        regionId: typeof h.regionId === 'string' && h.regionId.trim() ? h.regionId : region.id,
        date: resolvedDate,
        acqTimeUtc: resolvedAcqTime,
        dayNight: resolvedDayNight,
        year: resolvedYear,
        month: resolvedMonth,
        week:
          typeof h.week === 'number' && h.week >= 1 && h.week <= 52
            ? Math.round(h.week)
            : Math.min(52, Math.max(1, Math.ceil((resolvedMonth / 12) * 52))),
        lat: h.lat,
        lng: h.lng,
        sensor: h.sensor,
        frpMw: h.frpMw,
        frpUnit: 'MW',
        modisConfidencePct: modisConf,
        viirsConfidenceLevel: viirsConf,
        intensity:
          typeof h.intensity === 'number' && Number.isFinite(h.intensity)
            ? Math.min(1, Math.max(0, h.intensity))
            : Math.min(1, h.frpMw / 150),
        dataStatus: dataMode,
        satellite: typeof h.satellite === 'string' ? h.satellite : undefined,
        detectionType: h.detectionType === null || [0,1,2,3].includes(h.detectionType as number) ? h.detectionType as HotspotObservation['detectionType'] : undefined,
        harmonizedFrpMw: typeof h.harmonizedFrpMw === 'number' ? h.harmonizedFrpMw : null,
      });
    }

    // Validate annualSeries
    if (rd.annualSeries !== undefined && !Array.isArray(rd.annualSeries)) {
      return {
        ok: false,
        error: `Поле annualSeries в регионе "${region.name}" должно быть массивом`,
      };
    }
    const annualSeries: AnnualObservationPoint[] = Array.isArray(rd.annualSeries)
      ? rd.annualSeries.map((row: Record<string, unknown>) => ({
          year: Number(row.year),
          metricName:
            typeof row.metricName === 'string'
              ? row.metricName
              : 'Количество тепловых аномалий',
          metricUnit: typeof row.metricUnit === 'string' ? row.metricUnit : 'набл./год',
          modisCount: typeof row.modisCount === 'number' ? row.modisCount : null,
          viirsCount: typeof row.viirsCount === 'number' ? row.viirsCount : null,
          harmonizedCount:
            typeof row.harmonizedCount === 'number' ? row.harmonizedCount : null,
          harmonizedLowerCi:
            typeof row.harmonizedLowerCi === 'number' ? row.harmonizedLowerCi : null,
          harmonizedUpperCi:
            typeof row.harmonizedUpperCi === 'number' ? row.harmonizedUpperCi : null,
          modisMeanFrpMw:
            typeof row.modisMeanFrpMw === 'number'
              ? row.modisMeanFrpMw
              : typeof row.modisMeanFrp === 'number'
                ? row.modisMeanFrp
                : null,
          viirsMeanFrpMw:
            typeof row.viirsMeanFrpMw === 'number'
              ? row.viirsMeanFrpMw
              : typeof row.viirsMeanFrp === 'number'
                ? row.viirsMeanFrp
                : null,
          harmonizedMeanFrpMw:
            typeof row.harmonizedMeanFrpMw === 'number' ? row.harmonizedMeanFrpMw : null,
          completenessStatus: isValidCompleteness(row.completenessStatus)
            ? row.completenessStatus
            : 'complete',
          completenessNote:
            typeof row.completenessNote === 'string' ? row.completenessNote : undefined,
        }))
      : [];

    // Validate weeklyActivity
    if (rd.weeklyActivity !== undefined && !Array.isArray(rd.weeklyActivity)) {
      return {
        ok: false,
        error: `Поле weeklyActivity в регионе "${region.name}" должно быть массивом`,
      };
    }
    const weeklyActivity: WeeklyActivityPoint[] = Array.isArray(rd.weeklyActivity)
      ? rd.weeklyActivity.map((w: Record<string, unknown>) => ({
          year: Number(w.year),
          week: Number(w.week),
          metricName:
            typeof w.metricName === 'string' ? w.metricName : 'Тепловые детекции',
          metricUnit: typeof w.metricUnit === 'string' ? w.metricUnit : 'набл./нед.',
          modisCount: typeof w.modisCount === 'number' ? w.modisCount : null,
          viirsCount: typeof w.viirsCount === 'number' ? w.viirsCount : null,
          rawValue:
            w.rawValue === null ? null : typeof w.rawValue === 'number'
              ? w.rawValue
              : typeof w.modisCount === 'number' || typeof w.viirsCount === 'number'
                ? (typeof w.modisCount === 'number' ? w.modisCount : 0) +
                  (typeof w.viirsCount === 'number' ? w.viirsCount : 0)
                : null,
          harmonizedValue:
            typeof w.harmonizedValue === 'number' ? w.harmonizedValue : null,
          baselinePeriod:
            typeof w.baselinePeriod === 'string' ? w.baselinePeriod : null,
          comparableSeriesLabel:
            typeof w.comparableSeriesLabel === 'string' ? w.comparableSeriesLabel : null,
          historicalBaseline:
            typeof w.historicalBaseline === 'number' ? w.historicalBaseline : null,
          anomalyValue: typeof w.anomalyValue === 'number' ? w.anomalyValue : null,
          anomalyPct: typeof w.anomalyPct === 'number' ? w.anomalyPct : null,
          totalFrpMw: typeof w.totalFrpMw === 'number' ? w.totalFrpMw : null,
          completenessStatus: isValidCompleteness(w.completenessStatus)
            ? w.completenessStatus
            : 'complete',
          completenessNote:
            typeof w.completenessNote === 'string' ? w.completenessNote : undefined,
        }))
      : [];

    let harmonization: HarmonizationResult | null = null;
    if (rd.harmonization && typeof rd.harmonization === 'object' && !Array.isArray(rd.harmonization)) {
      const hRaw = rd.harmonization as Record<string, unknown>;
      const valRaw =
        (hRaw.validation && typeof hRaw.validation === 'object'
          ? hRaw.validation
          : hRaw.uncertainty && typeof hRaw.uncertainty === 'object'
            ? hRaw.uncertainty
            : {}) as Record<string, unknown>;

      const validation: HoldoutValidationMetrics = {
        holdoutPeriod:
          typeof valRaw.holdoutPeriod === 'string' ? valRaw.holdoutPeriod : null,
        holdoutSampleSize:
          typeof valRaw.holdoutSampleSize === 'number'
            ? valRaw.holdoutSampleSize
            : typeof valRaw.sampleSize === 'number'
              ? valRaw.sampleSize
              : null,
        mae: typeof valRaw.mae === 'number' ? valRaw.mae : null,
        rmse: typeof valRaw.rmse === 'number' ? valRaw.rmse : null,
        bias: typeof valRaw.bias === 'number' ? valRaw.bias : null,
        rSquared: typeof valRaw.rSquared === 'number' ? valRaw.rSquared : null,
        confidenceInterval95:
          typeof valRaw.confidenceInterval95 === 'string'
            ? valRaw.confidenceInterval95
            : null,
        unit:
          typeof valRaw.unit === 'string'
            ? valRaw.unit
            : typeof hRaw.metricUnit === 'string'
              ? hRaw.metricUnit
              : 'набл./год',
      };

      harmonization = {
        verified: false, // An uploaded boolean is not evidence of scientific validation.
        metricName:
          typeof hRaw.metricName === 'string'
            ? hRaw.metricName
            : 'Количество тепловых аномалий',
        metricUnit: typeof hRaw.metricUnit === 'string' ? hRaw.metricUnit : 'набл./год',
        overlapPeriod:
          Array.isArray(hRaw.overlapPeriod) &&
          hRaw.overlapPeriod.length === 2 &&
          typeof hRaw.overlapPeriod[0] === 'number' &&
          typeof hRaw.overlapPeriod[1] === 'number'
            ? [hRaw.overlapPeriod[0], hRaw.overlapPeriod[1]]
            : [2012, yearRangeRaw[1]],
        calibrationPeriod:
          Array.isArray(hRaw.calibrationPeriod) &&
          hRaw.calibrationPeriod.length === 2 &&
          typeof hRaw.calibrationPeriod[0] === 'number' &&
          typeof hRaw.calibrationPeriod[1] === 'number'
            ? [hRaw.calibrationPeriod[0], hRaw.calibrationPeriod[1]]
            : null,
        beforeValue: typeof hRaw.beforeValue === 'number' ? hRaw.beforeValue : null,
        afterValue: typeof hRaw.afterValue === 'number' ? hRaw.afterValue : null,
        methodName:
          typeof hRaw.methodName === 'string' && hRaw.methodName.trim()
            ? hRaw.methodName
            : 'Не задано',
        methodVersion:
          typeof hRaw.methodVersion === 'string' ? hRaw.methodVersion : null,
        methodologySummary:
          typeof hRaw.methodologySummary === 'string'
            ? hRaw.methodologySummary
            : 'Описание метода гармонизации не указано в JSON.',
        methodologySteps: Array.isArray(hRaw.methodologySteps)
          ? hRaw.methodologySteps.filter((s): s is string => typeof s === 'string')
          : [],
        limitations: Array.isArray(hRaw.limitations)
          ? hRaw.limitations.filter((s): s is string => typeof s === 'string')
          : undefined,
        validation,
      };
    }

    validatedDataByRegion[region.id] = {
      regionId: region.id,
      annualSeries,
      weeklyActivity,
      hotspots: validHotspots,
      harmonization,
    };
  }

  const resolvedSourceName =
    typeof obj.sourceName === 'string' && obj.sourceName.trim()
      ? obj.sourceName
      : dataMode === 'demo'
        ? 'DEMO · Демонстрационный набор'
        : 'Пользовательский JSON (Python)';

  const rawProv =
    obj.provenance && typeof obj.provenance === 'object' && !Array.isArray(obj.provenance)
      ? (obj.provenance as Record<string, unknown>)
      : null;

  const provenance: DatasetProvenanceMetadata = {
    sourceName:
      rawProv && typeof rawProv.sourceName === 'string' && rawProv.sourceName.trim()
        ? rawProv.sourceName
        : resolvedSourceName,
    productNames:
      rawProv && Array.isArray(rawProv.productNames)
        ? rawProv.productNames.filter((p): p is string => typeof p === 'string')
        : dataMode === 'demo'
          ? DEMO_DATASET.provenance.productNames
          : ['MODIS (MCD14ML)', 'VIIRS 375 m (VNP14IMG / VJ114IMG)'],
    observationPeriod:
      rawProv && typeof rawProv.observationPeriod === 'string'
        ? rawProv.observationPeriod
        : `${yearRangeRaw[0]}–${yearRangeRaw[1]}`,
    metricName:
      rawProv && typeof rawProv.metricName === 'string'
        ? rawProv.metricName
        : 'Количество тепловых аномалий и мощность FRP',
    metricUnit:
      rawProv && typeof rawProv.metricUnit === 'string' ? rawProv.metricUnit : 'набл. / МВт',
    processingMethod:
      rawProv && typeof rawProv.processingMethod === 'string'
        ? rawProv.processingMethod
        : null,
    limitations:
      rawProv && Array.isArray(rawProv.limitations)
        ? rawProv.limitations.filter((l): l is string => typeof l === 'string')
        : dataMode === 'demo'
          ? DEMO_DATASET.provenance.limitations
          : [
              'Тепловые аномалии отражают детектируемое спутником тепловое излучение и требуют наземной верификации причин.',
              'Облачность и время пролёта орбиты влияют на полноту суточной выборки.',
            ],
  };

  const rawSensors =
    obj.sensors && typeof obj.sensors === 'object' && !Array.isArray(obj.sensors)
      ? (obj.sensors as Record<string, Partial<SensorMetadata>>)
      : null;

  const sensors: Record<SatelliteSensor, SensorMetadata> = {
    MODIS: { ...DEMO_DATASET.sensors.MODIS, ...(rawSensors?.MODIS ?? {}) },
    VIIRS: { ...DEMO_DATASET.sensors.VIIRS, ...(rawSensors?.VIIRS ?? {}) },
  };

  return {
    ok: true,
    dataset: {
      schemaVersion: typeof obj.schemaVersion === 'string' ? obj.schemaVersion : '2.1.0',
      dataMode,
      sourceName: resolvedSourceName,
      generatedAt:
        typeof obj.generatedAt === 'string' ? obj.generatedAt : new Date().toISOString(),
      yearRange: [yearRangeRaw[0], yearRangeRaw[1]],
      provenance,
      sensors,
      regions: validatedRegions,
      dataByRegion: validatedDataByRegion,
    },
  };
}

export function filterHotspots(
  regionData: RegionDataset | undefined,
  query: FilterQuery,
  scope: 'singleYear' | 'period' = 'singleYear'
): HotspotObservation[] {
  if (!regionData) return [];

  const hasTimeFilter =
    query.timeStartHour != null &&
    query.timeEndHour != null &&
    !(query.timeStartHour === 0 && query.timeEndHour === 24);

  return regionData.hotspots.filter((spot) => {
    if (spot.regionId !== query.regionId) return false;
    if (query.regionBounds) {
      const { west, south, east, north } = query.regionBounds;
      if (spot.lng < west || spot.lng > east || spot.lat < south || spot.lat > north) {
        return false;
      }
    }
    if (!query.enabledSensors[spot.sensor]) return false;
    if (spot.intensity < query.minIntensity) return false;
    if (scope === 'singleYear') {
      if (spot.year !== query.selectedYear) return false;
    } else if (spot.year < query.startYear || spot.year > query.endYear) {
      return false;
    }
    if (query.weekFilter != null && spot.week !== query.weekFilter) return false;
    if (query.dateFrom && spot.date < query.dateFrom) return false;
    if (query.dateTo && spot.date > query.dateTo) return false;

    if (hasTimeFilter) {
      if (!spot.acqTimeUtc) return false;
      const hour = Number(spot.acqTimeUtc.slice(0, 2));
      if (Number.isNaN(hour)) return false;
      const startH = query.timeStartHour ?? 0;
      const endH = query.timeEndHour ?? 24;
      if (startH <= endH) {
        if (hour < startH || hour >= endH) return false;
      } else {
        // Wrap-around window (e.g. night 18:00..06:00 UTC)
        if (hour < startH && hour >= endH) return false;
      }
    }
    return true;
  });
}

export function filterAnnualSeries(
  regionData: RegionDataset | undefined,
  startYear: number,
  endYear: number
): AnnualObservationPoint[] {
  if (!regionData) return [];
  return regionData.annualSeries.filter((p) => p.year >= startYear && p.year <= endYear);
}

export interface ObservationSummary {
  /** Spatial map sample count (matches monthly chart & map points) */
  modisFilteredCount: number;
  viirsFilteredCount: number;
  totalFilteredCount: number;
  /** Full regional annual archive aggregate */
  annualModisAggregate: number | null;
  annualViirsAggregate: number | null;
  meanFrpMw: number | null;
  frpSampleSize: number;
  yearCompleteness: CompletenessStatus;
  yearCompletenessNote?: string;
}

/**
 * Computes strictly filter-synchronized spatial sample counts (n) alongside
 * full regional annual archive totals for the selected year.
 */
export function computeObservationSummary(
  regionData: RegionDataset | undefined,
  query: FilterQuery
): ObservationSummary {
  const spots = filterHotspots(regionData, query, 'singleYear');
  const modisSpots = spots.filter((s) => s.sensor === 'MODIS');
  const viirsSpots = spots.filter((s) => s.sensor === 'VIIRS');

  const yearRow = regionData?.annualSeries.find((r) => r.year === query.selectedYear);

  const annualModisAggregate = query.enabledSensors.MODIS
    ? (yearRow?.modisCount ?? null)
    : null;
  const annualViirsAggregate = query.enabledSensors.VIIRS
    ? (yearRow?.viirsCount ?? null)
    : null;

  const meanFrpMw =
    spots.length > 0
      ? Number((spots.reduce((sum, s) => sum + s.frpMw, 0) / spots.length).toFixed(1))
      : null;

  return {
    modisFilteredCount: modisSpots.length,
    viirsFilteredCount: viirsSpots.length,
    totalFilteredCount: spots.length,
    annualModisAggregate,
    annualViirsAggregate,
    meanFrpMw,
    frpSampleSize: spots.length,
    yearCompleteness: yearRow?.completenessStatus ?? (spots.length === 0 ? 'missing' : 'complete'),
    yearCompletenessNote: yearRow?.completenessNote,
  };
}

export function hotspotsToGeoJson(
  hotspots: HotspotObservation[]
): GeoJSON.FeatureCollection<GeoJSON.Point, HotspotObservation> {
  return {
    type: 'FeatureCollection',
    features: hotspots.map((spot) => ({
      type: 'Feature',
      properties: spot,
      geometry: {
        type: 'Point',
        coordinates: [spot.lng, spot.lat],
      },
    })),
  };
}

export function computeMapScaleLabel(zoom: number, latitude: number): string {
  const metersPerPixel =
    (156543.03392 * Math.cos((latitude * Math.PI) / 180)) / Math.pow(2, zoom);
  const targetMeters = metersPerPixel * 110;
  const targetKm = targetMeters / 1000;

  const niceSteps = [5, 10, 25, 50, 100, 250, 500, 1000, 2000, 5000];
  let best = niceSteps[0];
  for (const step of niceSteps) {
    if (Math.abs(step - targetKm) < Math.abs(best - targetKm)) {
      best = step;
    }
  }
  return `${best} км`;
}

